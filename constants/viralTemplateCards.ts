export type ViralTemplateFeature = 'generate' | 'retouch';

/** Card fields shown in pickers (no model prompt). */
export interface ViralTemplateCard {
  id: string;
  category: ViralTemplateCategory;
  feature: ViralTemplateFeature;
  titleKey: string;
  descriptionKey: string;
  thumbnailAltKey: string;
  aspectRatio?: '1:1' | '3:4' | '4:3' | '16:9' | '9:16';
  quantity?: 1 | 2 | 3 | 4;
  tab?: 'retouch' | 'adjust' | 'filters';
  thumbnail: string;
  tags: string[];
  supportsMultiPerson?: boolean;
}

/** Full template including English model prompt. */
export interface ViralTemplate extends ViralTemplateCard {
  prompt: string;
}

